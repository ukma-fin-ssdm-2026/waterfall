namespace Waterfall.Services.Llm;

/// <summary>
/// Причина, через яку жодна ланка ланцюжка не дала відповіді. Використовується
/// для перетворення збою LLM на 503 <c>LLM_UNAVAILABLE</c> (REL-003) без розкриття
/// тексту запиту або відповіді.
/// </summary>
public enum LlmFailureKind
{
    /// <summary>Для ролі немає жодної придатної ланки: порожній ланцюжок або в жодного провайдера немає ключа.</summary>
    NotConfigured,

    /// <summary>Вичерпано час очікування спроби або всього ланцюжка.</summary>
    Timeout,

    /// <summary>Провайдер повернув HTTP 429 (перевищено ліміт запитів).</summary>
    RateLimited,

    /// <summary>Провайдер повернув HTTP 5xx або стався збій мережі.</summary>
    ServerError
}
