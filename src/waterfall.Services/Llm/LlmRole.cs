namespace Waterfall.Services.Llm;

/// <summary>
/// Роль, під яку будується ланцюжок LLM-провайдерів (секція <c>Llm:Roles</c>).
/// Різні ролі мають різні вимоги до якості, швидкості та вартості моделі.
/// </summary>
public enum LlmRole
{
    /// <summary>Витяг структурованих фільтрів із вільного тексту запиту (дешева й швидка модель).</summary>
    Extract,

    /// <summary>Діалогова відповідь ШІ-консультанта (сильніша модель).</summary>
    Chat,

    /// <summary>Аналіз вимог вакансії (сильніша модель).</summary>
    Analyze
}
