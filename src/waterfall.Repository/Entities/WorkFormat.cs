namespace Waterfall.Repository.Entities;

/// <summary>
/// Формат роботи вакансії. Прапорці, бо джерела описують формат словами, і вакансія може дозволяти кілька
/// («Віддалено або офіс у Києві»): фільтр каталогу тоді працює як «будь-який із вибраних».
/// </summary>
[Flags]
public enum WorkFormat
{
    /// <summary>Формат не вказано.</summary>
    None = 0,

    /// <summary>Віддалена робота.</summary>
    Remote = 1,

    /// <summary>Гібридний формат: частина часу в офісі, частина — віддалено.</summary>
    Hybrid = 2,

    /// <summary>Робота в офісі.</summary>
    Office = 4
}
